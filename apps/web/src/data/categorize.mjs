/**
 * Trust per source field. <title> and og:site_name are the site's own name
 * for itself; the meta description is marketing copy; keywords are SEO
 * stuffing and therefore the weakest signal.
 */
const META_FIELD_WEIGHT = { title: 1, name: 1, description: 0.6, keywords: 0.3 };

/** Weighted evidence a category needs before it may be used. */
const META_MIN_SCORE = 3;

/**
 * Normalize free text for phrase matching: lowercase, diacritics removed
 * (so "noticias" also matches "notícias"), and every run of characters that
 * is neither a letter nor a digit collapses into a single space.
 */
function normalizeMetaText(s) {
  return String(s ?? '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

const phraseCache = new Map();

/**
 * Compiled matcher for one marker phrase. Latin phrases need letter
 * boundaries — "ai" must not match "email" or "said" — while non-latin
 * phrases (CJK, Arabic, …) are matched as plain substrings, because the
 * surrounding ideographs would break a letter-boundary test.
 */
function phraseMatcher(phrase) {
  let re = phraseCache.get(phrase);
  if (re) return re;
  const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  re = /[^\x00-\x7f]/.test(phrase)
    ? new RegExp(escaped, 'u')
    : new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, 'u');
  phraseCache.set(phrase, re);
  return re;
}

/**
 * Classify one site from its own self-description.
 * @param {string} [title] extracted <title> text
 * @param {{description?: string, ogSiteName?: string, appName?: string, keywords?: string}} [meta]
 *   the site's own meta description / og:site_name / keywords
 * @returns {string|undefined} a category slug, or undefined when the evidence
 *   is too weak or ambiguous
 */
function matchMeta(title, meta) {
  const fields = [
    ['title', title],
    ['name', meta?.ogSiteName ?? meta?.appName],
    ['description', meta?.description],
    ['keywords', meta?.keywords],
  ]
    .filter(([, v]) => typeof v === 'string' && v.trim())
    .map(([k, v]) => [k, normalizeMetaText(v)]);
  if (!fields.length) return undefined;

  const scores = new Map();
  const initiated = new Set();
  for (const [slug, weight, phrase] of META_MARKERS) {
    const p = normalizeMetaText(phrase);
    if (!p) continue;
    const re = phraseMatcher(p);
    for (const [field, text] of fields) {
      if (!re.test(text)) continue;
      scores.set(slug, (scores.get(slug) ?? 0) + weight * META_FIELD_WEIGHT[field]);
      // Only the site's own name fields may initiate a category, and only a
      // substantial marker counts: a stray weak word ("platform") in a title
      // must not start a classification on its own.
      if ((field === 'title' || field === 'name') && weight >= 2) initiated.add(slug);
      break;
    }
  }

  const candidates = [...scores.entries()]
    .filter(([slug, s]) => s >= META_MIN_SCORE && initiated.has(slug))
    .sort((a, b) => b[1] - a[1]);
  if (!candidates.length) return undefined;
  // A tie between two verticals means the evidence does not decide.
  if (candidates.length > 1 && candidates[0][1] === candidates[1][1]) return undefined;
  return candidates[0][0];
}

/**
 * Map one site to a category slug.
 * @param {string} domain lowercase domain, e.g. "github.com"
 * @param {string} [title] extracted <title> text, when the homepage was readable
 * @param {object} [meta] the site's own meta description / og:site_name /
 *   keywords — feeds the generalized meta pass; optional, so callers that
 *   only know the domain and the title keep working unchanged
 * @returns {string} one of CATEGORY_SLUGS
 */
export function categorize(domain, title, meta) {
  const lower = String(domain ?? '').toLowerCase();
  const labels = lower.split('.').filter(Boolean);
  if (labels.length === 0) return 'other';
  return (
    matchDomain(lower, labels) ??
    tldHint(labels) ??
    matchTitle(title) ??
    matchMeta(title, meta) ??
    'other'
  );
}
